subscribers = int(input("Введите количество подписчиков: "))

if subscribers >= 1000000:
    print("Ты звезда стриминга! Восхищаюсь тобой!")
elif subscribers >= 100000:
    print("Отличный результат! Ты уже известный стример.")
elif subscribers >= 10000:
    print("Хороший прогресс! Ещё немного — и популярность придёт.")
elif subscribers >= 1000:
    print("Неплохо для начала! Продолжай в том же духе.")
else:
    print("Все великие стримеры начинали с нуля. Не сдавайся!")
